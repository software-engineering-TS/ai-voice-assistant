import re
from pathlib import Path


class MetadataBuilder:
    """
    Builds metadata for each document chunk.

    Metadata is stored alongside each chunk in ChromaDB and is
    used for:

    - Document filtering
    - Source attribution
    - Duplicate detection
    - Document statistics
    """

    SHA256_PATTERN = re.compile(
        r"^[a-fA-F0-9]{64}$"
    )

    # ============================================================
    # Build Metadata
    # ============================================================

    def build(
        self,
        file_path: str,
        total_chunks: int,
        file_hash: str,
    ) -> list[dict]:
        """
        Build metadata for every document chunk.

        Parameters:
            file_path:
                Path to the uploaded document.

            total_chunks:
                Number of chunks generated by the text splitter.

            file_hash:
                SHA-256 hash calculated during document ingestion.

        Returns:
            One metadata dictionary per document chunk.
        """

        # --------------------------------------------------------
        # Validate File Path
        # --------------------------------------------------------

        if not isinstance(
            file_path,
            str,
        ):
            raise TypeError(
                "file_path must be a string."
            )

        file_path = file_path.strip()

        if not file_path:
            raise ValueError(
                "File path cannot be empty."
            )

        # --------------------------------------------------------
        # Validate Chunk Count
        # --------------------------------------------------------

        if not isinstance(
            total_chunks,
            int,
        ):
            raise TypeError(
                "total_chunks must be an integer."
            )

        if isinstance(
            total_chunks,
            bool,
        ):
            raise TypeError(
                "total_chunks must be an integer."
            )

        if total_chunks <= 0:
            raise ValueError(
                "total_chunks must be greater than zero."
            )

        # --------------------------------------------------------
        # Validate SHA-256 Hash
        # --------------------------------------------------------

        if not isinstance(
            file_hash,
            str,
        ):
            raise TypeError(
                "file_hash must be a string."
            )

        file_hash = file_hash.strip().lower()

        if not file_hash:
            raise ValueError(
                "file_hash cannot be empty."
            )

        if not self.SHA256_PATTERN.fullmatch(
            file_hash
        ):
            raise ValueError(
                "file_hash must be a valid SHA-256 hash."
            )

        # --------------------------------------------------------
        # Extract File Information
        # --------------------------------------------------------

        file_path_object = Path(
            file_path
        )

        file_name = (
            file_path_object.name
        )

        if not file_name:
            raise ValueError(
                "Unable to determine file name."
            )

        extension = (
            file_path_object.suffix
            .lower()
            .lstrip(".")
        )

        if not extension:
            raise ValueError(
                "Unable to determine file type."
            )

        # --------------------------------------------------------
        # Build Metadata
        # --------------------------------------------------------

        metadata: list[dict] = []

        for chunk_number in range(
            1,
            total_chunks + 1,
        ):

            metadata.append(
                {
                    "source": file_name,
                    "file_type": extension,
                    "chunk": chunk_number,
                    "file_hash": file_hash,
                }
            )

        return metadata


# ============================================================
# Shared Metadata Builder
# ============================================================

metadata_builder = MetadataBuilder()